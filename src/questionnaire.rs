#[derive(Debug, Clone, thiserror::Error)]
pub enum ValidationError {
    #[error("Question {question_id}: {message}")]
    InvalidAnswer {
        question_id: String,
        message: String,
    },

    #[error("Question {question_id} is required but was not answered")]
    MissingRequired { question_id: String },

    #[error("Visibility condition violated for question {question_id}: {message}")]
    VisibilityViolation {
        question_id: String,
        message: String,
    },
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Questionnaire {
    pub questions: Vec<Question>,
    pub version: String,
    pub title: String,
    pub description: String,
}

fn vis_eq(qid: &str, val: AnswerValue) -> Option<VisibilityCondition> {
    Some(VisibilityCondition {
        question_id: qid.to_string(),
        operator: ConditionOperator::Equals,
        value: val,
    })
}

fn vis_neq(qid: &str, val: AnswerValue) -> Option<VisibilityCondition> {
    Some(VisibilityCondition {
        question_id: qid.to_string(),
        operator: ConditionOperator::NotEquals,
        value: val,
    })
}

#[allow(dead_code)]
fn vis_gt(qid: &str, val: AnswerValue) -> Option<VisibilityCondition> {
    Some(VisibilityCondition {
        question_id: qid.to_string(),
        operator: ConditionOperator::GreaterThan,
        value: val,
    })
}

#[allow(dead_code)]
fn vis_contains(qid: &str, val: AnswerValue) -> Option<VisibilityCondition> {
    Some(VisibilityCondition {
        question_id: qid.to_string(),
        operator: ConditionOperator::Contains,
        value: val,
    })
}

fn none() -> Option<VisibilityCondition> {
    None
}

