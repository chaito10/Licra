impl Questionnaire {
    pub fn get_questions_for_category(&self, category: &QuestionCategory) -> Vec<&Question> {
        self.questions.iter().filter(|q| q.category == *category).collect()
    }

    pub fn get_question_by_id(&self, id: &str) -> Option<&Question> {
        self.questions.iter().find(|q| q.id == id)
    }

    pub fn get_categories(&self) -> Vec<QuestionCategory> {
        let mut cats: Vec<QuestionCategory> = self.questions.iter().map(|q| q.category.clone()).collect();
        cats.sort_by(|a, b| format!("{:?}", a).cmp(&format!("{:?}", b)));
        cats.dedup();
        cats
    }

    pub fn validate_answers(&self, answers: &[QuestionnaireAnswer]) -> Result<(), Vec<ValidationError>> {
        let mut errors = Vec::new();
        let answer_map: HashMap<&str, &AnswerValue> = answers.iter()
            .map(|a| (a.question_id.as_str(), &a.value))
            .collect();

        for question in &self.questions {
            if let Some(condition) = &question.visible_if {
                if let Some(dep_answer) = answer_map.get(condition.question_id.as_str()) {
                    if !self.evaluate_condition(dep_answer, &condition.operator, &condition.value) {
                        continue;
                    }
                } else {
                    continue;
                }
            }

            if let Some(answer) = answer_map.get(question.id.as_str()) {
                match &question.question_type {
                    QuestionType::Boolean => {
                        if !matches!(answer, AnswerValue::Boolean(_)) {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a boolean answer.".into() });
                        }
                    }
                    QuestionType::Text => {
                        if let AnswerValue::Text(t) = answer {
                            if t.is_empty() {
                                errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Text answer cannot be empty.".into() });
                            }
                        } else {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a text answer.".into() });
                        }
                    }
                    QuestionType::Choice => {
                        if let AnswerValue::Choice(c) = answer {
                            if !question.options.iter().any(|o| o.value == *c) {
                                errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: format!("Invalid choice: {}", c) });
                            }
                        } else {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a choice answer.".into() });
                        }
                    }
                    QuestionType::MultiChoice => {
                        if let AnswerValue::MultiChoice(mc) = answer {
                            for choice in mc {
                                if !question.options.iter().any(|o| o.value == *choice) {
                                    errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: format!("Invalid multi-choice: {}", choice) });
                                }
                            }
                        } else {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a multi-choice answer.".into() });
                        }
                    }
                    QuestionType::Number => {
                        if !matches!(answer, AnswerValue::Number(_)) {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a numeric answer.".into() });
                        }
                    }
                    QuestionType::Date => {
                        if !matches!(answer, AnswerValue::Date(_)) {
                            errors.push(ValidationError::InvalidAnswer { question_id: question.id.clone(), message: "Expected a date answer.".into() });
                        }
                    }
                }
            }
        }

        if errors.is_empty() {
            Ok(())
        } else {
            Err(errors)
        }
    }

    pub fn evaluate_visibility(&self, question: &Question, answers: &[QuestionnaireAnswer]) -> bool {
        if let Some(condition) = &question.visible_if {
            let answer_map: HashMap<&str, &AnswerValue> = answers.iter()
                .map(|a| (a.question_id.as_str(), &a.value))
                .collect();
            if let Some(dep_answer) = answer_map.get(condition.question_id.as_str()) {
                return self.evaluate_condition(dep_answer, &condition.operator, &condition.value);
            }
            return false;
        }
        true
    }

    pub fn search(&self, query: &str) -> Vec<&Question> {
        let q_lower = query.to_lowercase();
        self.questions.iter().filter(|question| {
            question.title.to_lowercase().contains(&q_lower)
                || question.description.to_lowercase().contains(&q_lower)
                || question.id.to_lowercase().contains(&q_lower)
        }).collect()
    }

    fn evaluate_condition(&self, answer: &AnswerValue, operator: &ConditionOperator, expected: &AnswerValue) -> bool {
        match operator {
            ConditionOperator::Equals => answer == expected,
            ConditionOperator::NotEquals => answer != expected,
            ConditionOperator::Contains => {
                if let (AnswerValue::Text(t), AnswerValue::Text(e)) = (answer, expected) {
                    t.to_lowercase().contains(&e.to_lowercase())
                } else if let (AnswerValue::MultiChoice(mc), AnswerValue::Choice(v)) = (answer, expected) {
                    mc.contains(v)
                } else {
                    false
                }
            }
            ConditionOperator::GreaterThan => {
                matches!((answer, expected), (AnswerValue::Number(a), AnswerValue::Number(e)) if a > e)
            }
            ConditionOperator::LessThan => {
                matches!((answer, expected), (AnswerValue::Number(a), AnswerValue::Number(e)) if a < e)
            }
        }
    }
}
